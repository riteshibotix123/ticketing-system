EXPORT = "/api/v1/reports/export"


@pytest.fixture
def world(db: Session) -> TicketWorld:
    return make_ticket_world(db)


def bearer(db: Session, user: User, clock: Clock, settings: Settings) -> dict[str, str]:
    db.commit()
    token = create_access_token(user.id, clock.now(), settings).token
    return {"Authorization": f"Bearer {token}"}


def export(
    client: TestClient,
    db: Session,
    clock: Clock,
    settings: Settings,
    user: User,
    params: Mapping[str, str],
) -> Response:
    response: Response = client.get(
        EXPORT, params=dict(params), headers=bearer(db, user, clock, settings)
    )
    return response


def csv_rows(response: Response) -> list[list[str]]:
    assert response.status_code == 200, response.text
    return list(csv.reader(io.StringIO(response.content.decode("utf-8"))))


def exported_numbers(rows: list[list[str]]) -> set[str]:
    return {row[0] for row in rows if row and row[0].startswith("IBX-")}


def audits(db: Session) -> list[AuditLog]:
    return list(db.scalars(select(AuditLog).where(AuditLog.action == "report_exported")))


def test_ticket_csv_has_header_block_rows_and_audit(
    client: TestClient, db: Session, clock: FrozenClock, settings: Settings, world: TicketWorld
) -> None:
    admin = world.users["admin"]
    response = export(
        client, db, clock, settings, admin, {"type": "tickets", "format": "csv", "scope": "all"}
    )
    rows = csv_rows(response)
    assert response.headers["content-type"] == "text/csv; charset=utf-8"
    assert (
        response.headers["content-disposition"]
        == 'attachment; filename="ibotix-tickets-20261027-1000.csv"'
    )
    assert rows[0] == ["Report", "Tickets"]
    assert rows[1] == ["Generated by", f"{admin.name} <{admin.email}>"]
    assert rows[2] == ["Generated at", "2026-10-27 10:00 +05:30"]
    assert rows[3] == ["Filters", "scope=all; sort=urgency"]
    assert rows[4] == ["Rows", "3"]
    assert rows[6][:3] == ["Ticket", "Title", "Department"]
    expected = {world.tickets[key].ticket_no for key in ("normal", "hr", "closed")}
    assert exported_numbers(rows) == expected
    normal = next(row for row in rows if row[:1] == [world.tickets["normal"].ticket_no])
    assert normal[1] == "Laptop screen flickers"
    assert normal[3] == "Hardware"
    assert normal[9] == world.users["assignee"].name
    [entry] = audits(db)
    assert entry.actor_id == admin.id
    assert entry.object_type == "report"
    assert entry.is_security_limited is False
    assert entry.new_value == {
        "type": "tickets",
        "format": "csv",
        "filters": {"scope": "all", "sort": "urgency"},
        "row_count": 3,
    }


def test_confidential_rows_only_for_those_who_see_them(
    client: TestClient, db: Session, clock: FrozenClock, settings: Settings, world: TicketWorld
) -> None:
    params = {"type": "tickets", "format": "csv", "scope": "all"}
    secret = world.tickets["secret"].ticket_no
    admin_rows = csv_rows(export(client, db, clock, settings, world.users["admin"], params))
    assert secret not in exported_numbers(admin_rows)
    assert "Sensitive matter" not in str(admin_rows)
    super_rows = csv_rows(export(client, db, clock, settings, world.users["super_admin"], params))
    assert secret in exported_numbers(super_rows)
    limited = {entry.actor_id: entry.is_security_limited for entry in audits(db)}
    assert limited == {world.users["admin"].id: False, world.users["super_admin"].id: True}


def test_xlsx_and_pdf_exports(
    client: TestClient, db: Session, clock: FrozenClock, settings: Settings, world: TicketWorld
) -> None:
    admin = world.users["admin"]
    xlsx = export(
        client, db, clock, settings, admin, {"type": "tickets", "format": "xlsx", "scope": "all"}
    )
    assert xlsx.status_code == 200, xlsx.text
    assert xlsx.headers["content-type"] == MEDIA_TYPES[ExportFormat.XLSX]
    assert xlsx.headers["content-disposition"].endswith('.xlsx"')
    sheet = load_workbook(io.BytesIO(xlsx.content))["Tickets"]
    values = [list(row) for row in sheet.iter_rows(values_only=True)]
    assert values[0][:2] == ["Report", "Tickets"]
    assert len([row for row in values if str(row[0]).startswith("IBX-")]) == 3
    pdf = export(client, db, clock, settings, admin, {"type": "kpis", "format": "pdf"})
    assert pdf.status_code == 200, pdf.text
    assert pdf.headers["content-type"] == "application/pdf"
    assert pdf.content.startswith(b"%PDF-")
    assert [
        entry.new_value["format"] for entry in audits(db) if isinstance(entry.new_value, dict)
    ] == [
        "xlsx",
        "pdf",
    ]


def test_kpi_csv_contains_sections_and_window(
    client: TestClient, db: Session, clock: FrozenClock, settings: Settings, world: TicketWorld
) -> None:
    rows = csv_rows(
        export(
            client,
            db,
            clock,
            settings,
            world.users["admin"],
            {"type": "kpis", "format": "csv", "department_id": "IT"},
        )
    )
    assert rows[0] == ["Report", "KPIs"]
    assert rows[3] == [
        "Filters",
        "from=2026-09-27T04:30:00Z; to=2026-10-27T04:30:00Z; department_ids=IT; priorities=",
    ]
    for title in ("Summary", "Initial response trend", "Aging", "Departments", "Top categories"):
        assert [title] in rows
    assert ["SLA met", "0"] in rows
    assert any(row[:2] == ["IT", "IT Department"] for row in rows)


def test_spoke_exports_only_their_departments(
    client: TestClient, db: Session, clock: FrozenClock, settings: Settings, world: TicketWorld
) -> None:
    spoke = world.users["spoke"]
    queue = csv_rows(
        export(
            client,
            db,
            clock,
            settings,
            spoke,
            {"type": "tickets", "format": "csv", "scope": "queue"},
        )
    )
    assert exported_numbers(queue) == {
        world.tickets["normal"].ticket_no,
        world.tickets["closed"].ticket_no,
    }
    make_ticket(db, spoke, world.hr, title="My own HR request")
    mine = csv_rows(
        export(
            client,
            db,
            clock,
            settings,
            spoke,
            {"type": "tickets", "format": "csv", "scope": "mine"},
        )
    )
    assert exported_numbers(mine) == set()
    for params in (
        {"type": "tickets", "format": "csv", "scope": "queue", "department_id": "HR"},
        {"type": "kpis", "format": "csv", "department_id": "HR"},
    ):
        response = export(client, db, clock, settings, spoke, params)
        assert response.status_code == 403
        assert response.json()["error"]["code"] == "forbidden"


