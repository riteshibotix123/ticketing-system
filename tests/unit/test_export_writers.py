import csv
import io
from datetime import UTC, datetime

import pytest
from openpyxl import load_workbook

from app.schemas.exports import ExportFormat
from app.services.exports.tables import Cell, Document, Table, build_document, ist_text
from app.services.exports.writers import (
    MEDIA_TYPES,
    csv_chunks,
    pdf_bytes,
    render,
    safe_cell,
    sheet_title,
    xlsx_bytes,
)

GENERATED_AT = datetime(2026, 10, 27, 4, 30, tzinfo=UTC)


def make_document(tables: list[Table]) -> Document:
    return build_document(
        "Tickets",
        "Priya Nair <priya.nair@ibotix.ai>",
        GENERATED_AT,
        {"scope": "all", "sort": "urgency"},
        tables,
    )


def sample() -> list[Table]:
    return [
        Table(
            "Tickets",
            ("Ticket", "Title", "Level"),
            [
                ("IBX-IT-2026-000001", '=HYPERLINK("x")', 2),
                ("IBX-IT-2026-000002", "Fine", None),
            ],
        )
    ]


@pytest.mark.parametrize(
    ("value", "expected"),
    [
        ("=SUM(A1)", "'=SUM(A1)"),
        ("+1", "'+1"),
        ("-2", "'-2"),
        ("@cmd", "'@cmd"),
        ("\tx", "'\tx"),
        ("\rx", "'\rx"),
        ("plain", "plain"),
        (-5, -5),
        (1.5, 1.5),
        (None, None),
    ],
)
def test_safe_cell_neutralises_formulas(value: Cell, expected: Cell) -> None:
    assert safe_cell(value) == expected


def test_header_block_lists_generator_time_filters_and_rows() -> None:
    document = make_document(sample())
    assert document.header == (
        ("Report", "Tickets"),
        ("Generated by", "Priya Nair <priya.nair@ibotix.ai>"),
        ("Generated at", "2026-10-27 10:00 +05:30"),
        ("Filters", "scope=all; sort=urgency"),
        ("Rows", "2"),
    )
    assert ist_text(None) is None


def test_csv_has_header_block_then_table() -> None:
    text = b"".join(csv_chunks(make_document(sample()))).decode("utf-8")
    rows = list(csv.reader(io.StringIO(text)))
    assert rows[:5] == [
        ["Report", "Tickets"],
        ["Generated by", "Priya Nair <priya.nair@ibotix.ai>"],
        ["Generated at", "2026-10-27 10:00 +05:30"],
        ["Filters", "scope=all; sort=urgency"],
        ["Rows", "2"],
    ]
    assert rows[5] == []
    assert rows[6] == ["Ticket", "Title", "Level"]
    assert rows[7] == ["IBX-IT-2026-000001", '\'=HYPERLINK("x")', "2"]
    assert rows[8] == ["IBX-IT-2026-000002", "Fine", ""]


def test_csv_titles_each_table_when_there_are_several() -> None:
    tables = [Table("Summary", ("Metric", "Value"), [("SLA met", 3)]), *sample()]
    rows = list(csv.reader(io.StringIO(b"".join(csv_chunks(make_document(tables))).decode())))
    assert ["Summary"] in rows
    assert ["Tickets"] in rows


def test_xlsx_puts_header_on_first_sheet_and_one_sheet_per_table() -> None:
    tables = [Table("Summary", ("Metric", "Value"), [("SLA met", 3)]), *sample()]
    workbook = load_workbook(io.BytesIO(xlsx_bytes(make_document(tables))))
    assert workbook.sheetnames == ["Summary", "Tickets"]
    first = [list(row) for row in workbook["Summary"].iter_rows(values_only=True)]
    assert first[0] == ["Report", "Tickets"]
    assert first[3] == ["Filters", "scope=all; sort=urgency"]
    assert first[6] == ["Metric", "Value"]
    tickets = [list(row) for row in workbook["Tickets"].iter_rows(values_only=True)]
    assert tickets[0] == ["Ticket", "Title", "Level"]
    assert tickets[1] == ["IBX-IT-2026-000001", '\'=HYPERLINK("x")', 2]


def test_sheet_titles_are_valid_and_unique() -> None:
    used: set[str] = set()
    long_name = "Workload by assignee and owner across departments"
    first = sheet_title(long_name, used)
    second = sheet_title(long_name, used)
    assert len(first) <= 31
    assert len(second) <= 31
    assert first != second
    assert sheet_title("A/B:C?", used) == "A B C"


def test_pdf_is_a_pdf_document() -> None:
    content = pdf_bytes(make_document(sample()))
    assert content.startswith(b"%PDF-")
    assert len(content) > 1000


@pytest.mark.parametrize("export_format", list(ExportFormat))
def test_render_returns_bytes_for_every_format(export_format: ExportFormat) -> None:
    content = b"".join(render(make_document(sample()), export_format))
    assert content
    assert export_format in MEDIA_TYPES
