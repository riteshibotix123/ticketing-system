type Cell = str | int | float | None
type Row = tuple[Cell, ...]

IST_SUFFIX: Final = "+05:30"
TICKET_COLUMNS: Final = (
    "Ticket",
    "Title",
    "Department",
    "Category",
    "Status",
    "Priority",
    "Confidential",
    "Requester",
    "Owner",
    "Assignee",
    "Created at",
    "Acknowledged at",
    "ETA",
    "SLA",
    "Escalation level",
    "Update overdue",
    "Resolved at",
    "Closed at",
    "Reopen count",
)


@dataclass(frozen=True, slots=True)
class Table:
    title: str
    columns: tuple[str, ...]
    rows: list[Row]


@dataclass(frozen=True, slots=True)
class Document:
    report: str
    header: tuple[tuple[str, str], ...]
    tables: tuple[Table, ...]


def ist_text(value: datetime | None) -> str | None:
    if value is None:
        return None
    return f"{to_ist(value):%Y-%m-%d %H:%M} {IST_SUFFIX}"


def yes_no(value: bool) -> str:
    return "Yes" if value else "No"


def row_count(tables: Iterable[Table]) -> int:
    return sum(len(table.rows) for table in tables)


def build_document(
    report: str,
    generated_by: str,
    generated_at: datetime,
    filters: Mapping[str, str],
    tables: Sequence[Table],
) -> Document:
    applied = "; ".join(f"{key}={value}" for key, value in filters.items())
    return Document(
        report=report,
        header=(
            ("Report", report),
            ("Generated by", generated_by),
            ("Generated at", ist_text(generated_at) or ""),
            ("Filters", applied),
            ("Rows", str(row_count(tables))),
        ),
        tables=tuple(tables),
    )


def ticket_table(
    tickets: Sequence[Ticket],
    users: Mapping[uuid.UUID, User],
    categories: Mapping[uuid.UUID, Category],
    timers: Mapping[uuid.UUID, Sequence[SlaTimer]],
) -> Table:
    def name(user_id: uuid.UUID | None) -> str | None:
        user = users.get(user_id) if user_id is not None else None
        return user.name if user is not None else None

    rows: list[Row] = []
    for ticket in tickets:
        category = categories.get(ticket.category_id) if ticket.category_id else None
        rows.append(
            (
                ticket.ticket_no,
                ticket.title,
                ticket.department_id,
                category.name if category is not None else None,
                ticket.status.value,
                ticket.priority.value,
                yes_no(ticket.confidential),
                name(ticket.requester_id),
                name(ticket.owner_id),
                name(ticket.assignee_id),
                ist_text(ticket.created_at),
                ist_text(ticket.acknowledged_at),
                ist_text(ticket.eta),
                build_sla_state(ticket, timers.get(ticket.id, ())).label,
                ticket.escalation_level,
                yes_no(ticket.update_overdue),
                ist_text(ticket.resolved_at),
                ist_text(ticket.closed_at),
                ticket.reopen_count,
            )
        )
    return Table("Tickets", TICKET_COLUMNS, rows)


def _duration_rows(label: str, duration: DurationOut) -> list[Row]:
    return [
        (f"{label}: count", duration.count),
        (f"{label}: average seconds", duration.avg_seconds),
        (f"{label}: median seconds", duration.median_seconds),
    ]


def _workload_rows(rows: Sequence[WorkloadRowOut], nobody: str) -> list[Row]:
    return [
        (row.user.name if row.user is not None else nobody, row.active, row.breached)
        for row in rows
    ]


def kpi_tables(report: KpiReportOut) -> tuple[Table, ...]:
    summary: list[Row] = [
        ("SLA met", report.sla_compliance.met),
        ("SLA missed", report.sla_compliance.missed),
        ("SLA compliance %", report.sla_compliance.pct),
        *_duration_rows("Initial response", report.initial_response),
        *_duration_rows("Resolution turnaround", report.resolution_turnaround),
        ("Resolved", report.reopen.resolved),
        ("Reopened", report.reopen.reopened),
        ("Reopen rate %", report.reopen.rate_pct),
        ("Escalations L1", report.escalations.l1),
        ("Escalations L2", report.escalations.l2),
        ("Escalations L3", report.escalations.l3),
        ("ETA breaches", report.eta_breach_count),
        ("Without update beyond threshold", report.stale_count),
        ("Overdue ETA", report.overdue_eta_count),
        ("Unacknowledged over 24h", report.unacknowledged_over_24h),
        ("Persistent L3", report.persistent_l3_count),
    ]
    return (
        Table("Summary", ("Metric", "Value"), summary),
        Table(
            "Initial response trend",
            ("Date", "Count", "Average seconds"),
            [
                (point.date, point.count, point.avg_seconds)
                for point in report.initial_response_trend
            ],
        ),
        Table(
            "Aging", ("Bucket (days)", "Count"), [(row.bucket, row.count) for row in report.aging]
        ),
        Table(
            "Departments",
            (
                "Department",
                "Name",
                "Active",
                "Low",
                "Medium",
                "High",
                "Critical",
                "On track",
                "Warning",
                "Breached",
                "SLA compliance %",
            ),
            [
                (
                    row.department_id,
                    row.name,
                    row.active,
                    row.by_priority.low,
                    row.by_priority.medium,
                    row.by_priority.high,
                    row.by_priority.critical,
                    row.on_track,
                    row.warning,
                    row.breached,
                    row.sla_met_pct,
                )
                for row in report.departments
            ],
        ),
        Table(
            "Workload by assignee",
            ("Assignee", "Active", "Breached"),
            _workload_rows(report.workload.by_assignee, "Unassigned"),
        ),
        Table(
            "Workload by owner",
            ("Owner", "Active", "Breached"),
            _workload_rows(report.workload.by_owner, "No owner"),
        ),
        Table(
            "Top categories",
            ("Category", "Count"),
            [(row.name, row.count) for row in report.top_categories],
        ),
    )
